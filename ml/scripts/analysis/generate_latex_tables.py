"""Generate LaTeX (booktabs) tables from parsed_results.json files.

Reads one or more parsed_results.json (output of parse_loso_results.py) and
emits LaTeX tables ready to drop into Ch5 of the thesis.

Usage:
    python generate_latex_tables.py \\
        --parsed runs/detect/runs/level1/parsed_results.json \\
        --parsed runs/detect/runs/level1_tuned/parsed_results.json \\
        --parsed runs/rtdetr/parsed_results.json \\
        --out-tex docs/thesis/chapters/_tables_generated.tex

Then `\\input{chapters/_tables_generated}` in 05_experiments.tex.
"""

from __future__ import annotations

import json
from pathlib import Path

import click


CAM_BY_FOLD = {0: "cam\\_1", 1: "cam\\_2", 2: "cam\\_3", 3: "cam\\_5", 4: "cam\\_7"}


def fmt(mean: float, std: float | None = None) -> str:
    if std is None or std == 0:
        return f"{mean:.3f}"
    return f"{mean:.3f} $\\pm$ {std:.3f}"


def per_fold_table(label: str, summary: dict, caption: str) -> str:
    lines = [
        f"\\begin{{table}}[h]",
        f"\\centering",
        f"\\caption{{{caption}}}",
        f"\\label{{{label}}}",
        f"\\begin{{tabular}}{{lcccccc}}",
        f"\\toprule",
        f"Fold & Test cam & mAP@50 & mAP@50:95 & P & R & best epoch (seeds) \\\\",
        f"\\midrule",
    ]
    for fold in sorted(summary["folds"].keys()):
        f = summary["folds"][fold]
        be = "/".join(str(e) for e in f.get("best_epochs", []))
        m50 = fmt(f.get("mAP50_mean", 0), f.get("mAP50_std"))
        m95 = fmt(f.get("mAP50_95_mean", 0), f.get("mAP50_95_std"))
        prec = fmt(f.get("precision_mean", 0))
        rec = fmt(f.get("recall_mean", 0))
        lines.append(
            f"{fold} & {CAM_BY_FOLD.get(fold, '?')} & {m50} & {m95} & {prec} & {rec} & {be} \\\\"
        )
    loso = summary["loso_mean"]
    lines.append(f"\\midrule")
    lines.append(
        f"\\textbf{{LOSO mean}} & --- & "
        f"\\textbf{{{fmt(loso['mAP50_mean'], loso['mAP50_std'])}}} & "
        f"\\textbf{{{fmt(loso['mAP50_95_mean'], loso['mAP50_95_std'])}}} & "
        f"\\textbf{{{fmt(loso['precision_mean'])}}} & "
        f"\\textbf{{{fmt(loso['recall_mean'])}}} & --- \\\\"
    )
    lines += [f"\\bottomrule", f"\\end{{tabular}}", f"\\end{{table}}", ""]
    return "\n".join(lines)


def headline_table(summaries: dict[str, dict], label: str = "tab:headline") -> str:
    lines = [
        f"\\begin{{table}}[h]",
        f"\\centering",
        f"\\caption{{Headline LOSO comparison across configurations.}}",
        f"\\label{{{label}}}",
        f"\\begin{{tabular}}{{lcccc}}",
        f"\\toprule",
        f"Configuration & N runs & mAP@50 & mAP@50:95 & R(overall) \\\\",
        f"\\midrule",
    ]
    for config_label, summary in summaries.items():
        loso = summary["loso_mean"]
        lines.append(
            f"{config_label} & {loso.get('n_runs_total', '?')} & "
            f"{fmt(loso['mAP50_mean'], loso['mAP50_std'])} & "
            f"{fmt(loso['mAP50_95_mean'], loso['mAP50_95_std'])} & "
            f"{fmt(loso['recall_mean'])} \\\\"
        )
    lines += [f"\\bottomrule", f"\\end{{tabular}}", f"\\end{{table}}", ""]
    return "\n".join(lines)


CONFIG_LABEL = {
    "level1_baseline": "YOLOv8m baseline (Level-1)",
    "level1_tuned": "YOLOv8m tuned (Level-1.5: lr0=0.001, warmup=5, patience=50)",
    "rtdetr_baseline": "RT-DETR-L (Level-1.5 sister)",
    "level1_lr001": "YOLOv8m lr0=0.001 sanity",
}


@click.command()
@click.option(
    "--parsed",
    "parsed_paths",
    multiple=True,
    type=click.Path(path_type=Path, exists=True),
    required=True,
    help="One or more parsed_results.json paths.",
)
@click.option(
    "--out-tex",
    type=click.Path(path_type=Path),
    default=Path("docs/thesis/chapters/_tables_generated.tex"),
)
def main(parsed_paths: tuple[Path, ...], out_tex: Path) -> None:
    out_tex.parent.mkdir(parents=True, exist_ok=True)
    summaries: dict[str, dict] = {}
    for p in parsed_paths:
        data = json.loads(p.read_text())
        for cfg, summary in data.get("summary", {}).items():
            summaries[cfg] = summary

    if not summaries:
        click.echo("No summaries found in parsed JSONs.")
        return

    click.echo(f"Loaded {len(summaries)} configs: {list(summaries.keys())}")

    headline_label_map = {CONFIG_LABEL.get(k, k): v for k, v in summaries.items()}
    out = ["% Auto-generated by scripts/analysis/generate_latex_tables.py", ""]
    out.append(headline_table(headline_label_map, label="tab:headline-results-auto"))

    for cfg, summary in summaries.items():
        label = f"tab:per-fold-{cfg}"
        caption = (
            f"Per-fold mean $\\pm$ std for {CONFIG_LABEL.get(cfg, cfg)}. "
            f"Best epoch column lists per-seed convergence epoch."
        )
        out.append(per_fold_table(label, summary, caption))

    out_tex.write_text("\n".join(out))
    click.echo(f"\nWrote: {out_tex}")


if __name__ == "__main__":
    main()
